/**
 * Generator + DRIFT TEST for lib/agents/harness/requirements-form-check.generated.ts (2026-10-09).
 *
 * The in-run requirements form check needs two inputs that live in documents, not code:
 *   1. the REGISTRY (`.claude/knowledge/pipelines/requirements-authoring/DESIGN-DECISION-QUESTIONS.md`, REGISTRY-TABLE) —
 *      the leg-scoped key classes and each key's options cell (coverage 8.1 / options == registry);
 *   2. the public TEMPLATE text (`~/paichart/program-artifacts/_TEMPLATE/requirements.template.md`) — the harvested-state
 *      lint's allowlist base (a token the template carries is a synthetic example, not harvested state).
 * Both are baked into a generated TS constant so the check does no I/O on the hot path and a replay of an old fact can
 * name exactly which registry it ran against (`registrySha256` / `templateSha256` are stamped on the fact).
 *
 *   npx ts-node … scripts/generate-requirements-form-check-data.ts           # regenerate
 *   npx ts-node … scripts/generate-requirements-form-check-data.ts --check   # DRIFT TEST: exit 1 if stale
 *
 * The template half needs the public repo (PAICHART_PUBLIC_REPO or ~/paichart). When it is absent, --check SKIPS THAT
 * HALF BY NAME and says so (the skeleton-parity rule: a skip is reported, never silent); the registry half always runs.
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';
import { createHash } from 'crypto';
import * as os from 'os';
import { parseRegistry } from '../lib/agents/harness/requirements-coverage';

const ROOT = join(__dirname, '..');
const REGISTRY_DOC = join(ROOT, '.claude', 'knowledge', 'pipelines', 'requirements-authoring', 'DESIGN-DECISION-QUESTIONS.md');
const REPO = process.env.PAICHART_PUBLIC_REPO || join(os.homedir(), 'paichart');
const TEMPLATE = join(REPO, 'program-artifacts', '_TEMPLATE', 'requirements.template.md');
const OUT = join(ROOT, 'lib', 'agents', 'harness', 'requirements-form-check.generated.ts');
/** G5 (2026-10-10, EF F4(c)): the PUBLIC source the size + lint port mirrors. Its sha is recorded so the out-of-CI
 *  --check names WHICH side moved when the Python reference changes without a TS mirror. */
const RULES_PY = join(REPO, 'scripts', 'requirements-rules.py');

const sha = (s: string) => createHash('sha256').update(s, 'utf8').digest('hex');

function render(registryText: string, templateText: string, rulesPyText: string): string {
  const reg = parseRegistry(registryText);
  return `/* eslint-disable */
// GENERATED by scripts/generate-requirements-form-check-data.ts — DO NOT EDIT BY HAND.
// Drift test: npm run test:requirements-form-check-data (fails when either source changed without regeneration).
// Sources: .claude/knowledge/pipelines/requirements-authoring/DESIGN-DECISION-QUESTIONS.md (REGISTRY-TABLE)
//          paichart/paichart program-artifacts/_TEMPLATE/requirements.template.md (lint allowlist base)
import type { RequirementsRegistry } from './requirements-coverage';

export const REQUIREMENTS_REGISTRY_SHA256 = ${JSON.stringify(sha(JSON.stringify(reg)))}; // sha of the PARSED registry — a prose edit to the doc is not drift
export const REQUIREMENTS_REGISTRY: RequirementsRegistry = ${JSON.stringify(reg, null, 1)};

export const REQUIREMENTS_TEMPLATE_SHA256 = ${JSON.stringify(sha(templateText))};
export const REQUIREMENTS_TEMPLATE_TEXT: string = ${JSON.stringify(templateText)};

// sha of paichart/paichart scripts/requirements-rules.py at the last regeneration — the size + lint port's reference.
export const REQUIREMENTS_RULES_PY_SHA256 = ${JSON.stringify(sha(rulesPyText))};
`;
}

function main(): number {
  const check = process.argv.includes('--check');
  const registryText = readFileSync(REGISTRY_DOC, 'utf8');
  if (!check) {
    if (!existsSync(TEMPLATE)) { console.error(`✗ template not found: ${TEMPLATE} (set PAICHART_PUBLIC_REPO)`); return 2; }
    if (!existsSync(RULES_PY)) { console.error(`✗ rules script not found: ${RULES_PY} (set PAICHART_PUBLIC_REPO)`); return 2; }
    writeFileSync(OUT, render(registryText, readFileSync(TEMPLATE, 'utf8'), readFileSync(RULES_PY, 'utf8')));
    console.log(`✓ wrote ${OUT}`);
    return 0;
  }
  const gen = require('../lib/agents/harness/requirements-form-check.generated');
  let failed = 0;
  const ok = (name: string, pass: boolean, detail = '') => { console.log(`${pass ? '✅' : '❌'} ${name}${!pass && detail ? ` — ${detail}` : ''}`); if (!pass) failed++; };
  const fresh = parseRegistry(registryText);
  ok('registry: generated constant equals a fresh parse of DESIGN-DECISION-QUESTIONS.md',
    JSON.stringify(gen.REQUIREMENTS_REGISTRY) === JSON.stringify(fresh), 'the REGISTRY-TABLE changed — run the generator');
  ok('registry: stamped sha is the sha of the embedded registry', gen.REQUIREMENTS_REGISTRY_SHA256 === sha(JSON.stringify(gen.REQUIREMENTS_REGISTRY)));
  ok('template: embedded text is self-consistent (sha)', gen.REQUIREMENTS_TEMPLATE_SHA256 === sha(gen.REQUIREMENTS_TEMPLATE_TEXT));
  if (existsSync(TEMPLATE)) {
    ok('template: generated constant matches the public template', gen.REQUIREMENTS_TEMPLATE_SHA256 === sha(readFileSync(TEMPLATE, 'utf8')),
      `${TEMPLATE} changed — run the generator`);
  } else {
    console.log(`⏭️  SKIPPED (named): template upstream parity — ${TEMPLATE} not present (set PAICHART_PUBLIC_REPO)`);
  }
  if (existsSync(RULES_PY)) {
    ok('rules: requirements-rules.py is the version the size + lint port was last checked against', gen.REQUIREMENTS_RULES_PY_SHA256 === sha(readFileSync(RULES_PY, 'utf8')),
      `${RULES_PY} changed — mirror the change in requirements-size-lint.ts, run test:requirements-form-check-parity, then regenerate`);
  } else {
    console.log(`⏭️  SKIPPED (named): rules upstream parity — ${RULES_PY} not present (set PAICHART_PUBLIC_REPO)`);
  }
  console.log(failed ? `\n❌ ${failed} drift check(s) failed` : '\n✅ requirements form-check data is current');
  return failed ? 1 : 0;
}

process.exit(main());
