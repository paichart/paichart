#!/usr/bin/env ts-node
/**
 * measure-quote-pairing-tie.ts — QUOTE-PAIRING-TIE measurement (2026-11-01, execution-facts). READ-ONLY.
 *
 * Question: how often does a quoteFidelity block tie on the DOCUMENT choice (two raw documents with the same line-set
 * count), and what would breaking that tie by (in-order matched, then gapCost) change?
 *
 * Shipping matcher, never a re-implementation: inputs are captured from the SHIPPING replay path (`replay()` in
 * scripts/replay-nets.ts → MECHANICAL_NETS → computeQuoteFidelity / computeAuthorQuoteFidelityFact), and the matcher is a
 * copy of lib/agents/harness/quote-fidelity.ts generated by EXACT text patches (each asserted to apply exactly once):
 *   - a passive recorder (per block: every document's line-set count, the chosen document, each tied document's own
 *     evaluation) — output unchanged, proven per task by CONTROL 0 (copy in `ship` mode === shipping, byte for byte);
 *   - the candidate tie-break, active only in `tiebreak` mode.
 *
 * Run against the read-only nets-replay snapshot DB (never production):
 *   QPT_DBURL_FILE=<file holding the scratch DB URL> QPT_OUT=<scratch dir> \
 *     TS_NODE_TRANSPILE_ONLY=1 npx ts-node --compiler-options '{"module":"commonjs"}' scripts/measure-quote-pairing-tie.ts
 * Output: <QPT_OUT>/rows.jsonl (one row per task), <QPT_OUT>/ties.jsonl (one row per tied block), summary on stdout.
 */
import * as fs from 'fs';
import * as path from 'path';

const urlFile = process.env.QPT_DBURL_FILE;
const outDir = process.env.QPT_OUT;
if (!urlFile || !outDir) { console.error('need QPT_DBURL_FILE and QPT_OUT'); process.exit(2); }
const dbUrl = fs.readFileSync(urlFile, 'utf8').trim();
if (!/@(localhost|127\.0\.0\.1)[:/]/.test(dbUrl) || !/\/nets_replay_/.test(dbUrl)) { console.error('✗ ABORT: not a local nets_replay_* snapshot DB'); process.exit(2); }
process.env.DATABASE_URL = dbUrl; // before replay-nets loads dotenv (which never overrides) and its PrismaClient
fs.mkdirSync(outDir, { recursive: true });

// ── 1. the instrumented copy ─────────────────────────────────────────────────────────────────────────────────────────
const HARNESS = path.resolve(__dirname, '../lib/agents/harness');
let src = fs.readFileSync(path.join(HARNESS, 'quote-fidelity.ts'), 'utf8');
const patch = (from: string, to: string) => {
  const n = src.split(from).length - 1;
  if (n !== 1) { console.error(`✗ patch anchor found ${n} times (need 1): ${from.slice(0, 80)}`); process.exit(1); }
  src = src.replace(from, () => to);
};
// relative imports → absolute paths of the shipping modules
src = src.replace(/from '\.\/([^']+)'/g, (_m, p) => `from '${path.join(HARNESS, p)}'`);
patch('function prepare(', 'export function prepare(');
patch('const qnorm = ', 'export const qnorm = ');
patch('/** Analyse ONE block against the prepared raw documents. Exported for the fixtures. */',
  `export const __qpt: { mode: 'ship' | 'tiebreak'; rec: any[] | null; forced: boolean } = { mode: 'ship', rec: null, forced: false };
let __lastEv: { matched: number; gapCost: number; findingCount: number } | null = null;
const __sum = (r: BlockResult) => (!r.pairable ? 'unpairable' : !r.finding ? 'complete'
  : { totals: r.finding.totals, span: r.finding.span, claim: r.finding.claim, escalates: r.finding.escalates, source: r.finding.source,
      omitted: r.finding.omitted, added: r.finding.added, changed: r.finding.changed });
/** Analyse ONE block against the prepared raw documents. Exported for the fixtures. */`);
patch(`  if (!best || bestM < MIN_PAIR_LINES || bestM * 2 < nb.length) return { pairable: false };
`, `  const __counts = prepared.map((p) => { let m = 0; for (const q of qn) if (p.set.has(q)) m++; return m; });
  const __pairable = !!best && bestM >= MIN_PAIR_LINES && bestM * 2 >= nb.length;
  const __tied = __pairable ? prepared.filter((_, i) => __counts[i] === bestM) : [];
  let __entry: any = null;
  if (!__qpt.forced && __qpt.rec) {
    __entry = { blockLine: block.blockLine, label: block.label, nb: nb.length, bestM, pairable: __pairable,
      chosen: best ? prepared.indexOf(best) : -1,
      docs: prepared.map((p, i) => ({ i, m: __counts[i], origin: p.doc.origin, call: p.doc.call, tool: p.doc.tool,
        resolvedService: p.doc.resolvedService, path: p.doc.path, lane: laneOf(p.doc), lines: p.doc.lines.length })).filter((d) => d.m > 0),
      perDoc: null as any };
    __qpt.rec.push(__entry);
  }
  if (!__qpt.forced && __tied.length > 1) {
    const per: Array<{ i: number; r: BlockResult; ev: { matched: number; gapCost: number; findingCount: number } }> = [];
    for (const p of __tied) {
      __qpt.forced = true;
      try { const r = analyseBlock(block, [p]); per.push({ i: prepared.indexOf(p), r, ev: __lastEv! }); } finally { __qpt.forced = false; }
    }
    let win = per[0];
    for (const x of per.slice(1)) if (x.ev.matched > win.ev.matched || (x.ev.matched === win.ev.matched && x.ev.gapCost < win.ev.gapCost)) win = x;
    if (__entry) __entry.perDoc = per.map((x) => ({ i: x.i, ev: x.ev, result: __sum(x.r) })), __entry.tiebreakChoice = win.i;
    if (__qpt.mode === 'tiebreak') return win.r;
  }
  if (!best || bestM < MIN_PAIR_LINES || bestM * 2 < nb.length) return { pairable: false };
`);
patch('  const { findingCount, lo, hi, wholeDoc, omitted, changed, added, elisions } = ev;\n',
  '  const { findingCount, lo, hi, wholeDoc, omitted, changed, added, elisions } = ev;\n  __lastEv = { matched: ev.matched, gapCost: ev.gapCost, findingCount: ev.findingCount };\n');
const copyDir = path.join(outDir, 'instrumented');
fs.mkdirSync(copyDir, { recursive: true });
const copyPath = path.join(copyDir, 'quote-fidelity-instrumented.ts');
fs.writeFileSync(copyPath, src);

// eslint-disable-next-line @typescript-eslint/no-var-requires
require('tsconfig-paths/register');
// eslint-disable-next-line @typescript-eslint/no-var-requires
const copy = require(copyPath);
// eslint-disable-next-line @typescript-eslint/no-var-requires
const shipping = require('../lib/agents/harness/quote-fidelity');
const shippingCompute = shipping.computeQuoteFidelity;
let captured: unknown[] = [];
shipping.computeQuoteFidelity = (input: unknown) => { captured.push(input); return shippingCompute(input); };
if (shipping.computeQuoteFidelity === shippingCompute) { console.error('✗ could not wrap the shipping export'); process.exit(1); }
// eslint-disable-next-line @typescript-eslint/no-var-requires
const { replay } = require('./replay-nets');
// eslint-disable-next-line @typescript-eslint/no-var-requires
const { PrismaClient } = require('@prisma/client');
const db = new PrismaClient({ datasources: { db: { url: dbUrl } } });

const pickLeg = (f: any) => ({
  checked: f?.checked, reason: f?.reason, escalating: f?.blocks?.escalating ?? null, withFindings: f?.blocks?.withFindings ?? null,
  disposition: f?.quoteFidelityDisposition?.disposition ?? null, dispositionReason: f?.quoteFidelityDisposition?.reason ?? null,
  deviceEscalating: f?.deviceReads?.escalating ?? null,
});
const findingAt = (f: any, line: number) => (Array.isArray(f?.findings) ? f.findings.find((x: any) => x.blockLine === line) ?? null : null);

(async () => {
  const pop: Array<{ tid: string; role: string; stored_version: string | null; protocol: string | null; leg: string | null }> = await db.$queryRawUnsafe(`
    WITH s AS (
      SELECT DISTINCT ON (e."taskId") e."taskId" tid, a.content::jsonb->'quoteFidelity'->>'version' stored_version
      FROM agent_artifacts a JOIN agent_executions e ON e.id = a."executionId"
      WHERE a.name = 'result.json' AND a.content LIKE '{%' AND a.content LIKE '%"quoteFidelity"%'
      ORDER BY e."taskId", a."createdAt" DESC)
    SELECT s.tid, t."agentRole" role, s.stored_version, l.metadata->>'protocol' protocol, l.id leg
    FROM s JOIN tasks t ON t.id = s.tid
    LEFT JOIN tasks l ON l.type = 'PIPELINE' AND l.metadata->>'pipelineStageId' = t.stage_id
    ORDER BY s.tid`);
  const rowsOut = fs.createWriteStream(path.join(outDir, 'rows.jsonl'));
  const tiesOut = fs.createWriteStream(path.join(outDir, 'ties.jsonl'));
  const blocksOut = fs.createWriteStream(path.join(outDir, 'blocks.jsonl'));
  let control0Fail = 0;
  const origLog = console.log;
  for (const t of pop) {
    captured = [];
    console.log = () => undefined;
    let replayError: string | null = null;
    try { await replay(t.tid, 'quoteFidelity', false, db); } catch (e) { replayError = String(e); } finally { console.log = origLog; }
    const row: any = { ...t, replayError, inputs: captured.length, control0: null, ship: null, tiebreak: null, blocks: [], ties: 0, docChanged: 0, movers: [] };
    for (const input of captured) {
      const shipFact = shippingCompute(input);
      copy.__qpt.mode = 'ship'; copy.__qpt.rec = [];
      const copyShip = copy.computeQuoteFidelity(input);
      const rec: any[] = copy.__qpt.rec; copy.__qpt.rec = null;
      const same = JSON.stringify(shipFact) === JSON.stringify(copyShip);
      if (!same) control0Fail++;
      row.control0 = row.control0 === false ? false : same;
      copy.__qpt.mode = 'tiebreak';
      const tbFact = copy.computeQuoteFidelity(input);
      copy.__qpt.mode = 'ship';
      row.ship = pickLeg(shipFact); row.tiebreak = pickLeg(tbFact);
      row.legOutcomeMoved = JSON.stringify(row.ship) !== JSON.stringify(row.tiebreak);
      row.factMoved = JSON.stringify(shipFact) !== JSON.stringify(tbFact);
      if (row.factMoved) {
        row.factDiff = {};
        for (const k of new Set([...Object.keys(shipFact), ...Object.keys(tbFact)])) {
          if (JSON.stringify(shipFact[k]) !== JSON.stringify(tbFact[k])) row.factDiff[k] = { ship: shipFact[k], tiebreak: tbFact[k] };
        }
      }
      for (const b of rec) {
        row.blocks.push({ blockLine: b.blockLine, pairable: b.pairable, candidates: b.docs.length, bestM: b.bestM, nb: b.nb });
        blocksOut.write(JSON.stringify({ tid: t.tid, role: t.role, protocol: t.protocol, point: (input as any).point, blockLine: b.blockLine,
          label: b.label.slice(0, 200), nb: b.nb, bestM: b.bestM, pairable: b.pairable, chosen: b.chosen, tied: !!b.perDoc,
          docs: b.docs.map((d: any) => ({ i: d.i, m: d.m, lane: d.lane, service: d.resolvedService, tool: d.tool, origin: d.origin, path: d.path })) }) + '\n');
        if (!b.perDoc) continue;
        row.ties++;
        const changedDoc = b.tiebreakChoice !== b.chosen;
        if (changedDoc) row.docChanged++;
        const fShip = findingAt(shipFact, b.blockLine), fTb = findingAt(tbFact, b.blockLine);
        const blockMoved = JSON.stringify(fShip) !== JSON.stringify(fTb);
        const mover = changedDoc && (blockMoved || row.legOutcomeMoved);
        const tie = { tid: t.tid, role: t.role, protocol: t.protocol, leg: t.leg, storedVersion: t.stored_version, point: (input as any).point,
          blockLine: b.blockLine, label: b.label, nb: b.nb, bestM: b.bestM, chosen: b.chosen, tiebreakChoice: b.tiebreakChoice,
          changedDoc, blockMoved, legOutcomeMoved: row.legOutcomeMoved, mover,
          tied: b.perDoc.map((p: any) => ({ ...b.docs.find((d: any) => d.i === p.i), ev: p.ev, result: p.result })),
          otherCandidates: b.docs.filter((d: any) => !b.perDoc.some((p: any) => p.i === d.i)) };
        tiesOut.write(JSON.stringify(tie) + '\n');
        if (mover) row.movers.push(b.blockLine);
      }
    }
    rowsOut.write(JSON.stringify(row) + '\n');
  }
  rowsOut.end(); tiesOut.end(); blocksOut.end();
  await new Promise((r) => setTimeout(r, 200));
  console.log(`tasks ${pop.length} · control0 failures ${control0Fail}`);
  await db.$disconnect();
  process.exit(0);
})();
