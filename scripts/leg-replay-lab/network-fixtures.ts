/** The device pool from CACHED production snapshots (read-only, no network): every successful single-target `fetch_data` and every
 *  `list_devices` of the named executions, first occurrence per key, inner result verbatim. */
export function buildDevicePool(sources: Array<{ executionId: string; toolCalls: Array<Record<string, any>> }>, serviceNames: string[], failure?: DevicePool['failure']): DevicePool {
  const entries: DevicePoolEntry[] = [];
  for (const s of sources) s.toolCalls.forEach((t, index) => {
    if (t?.tool !== 'services' || t.success === false) return;
    const a = asObj(t.arguments) ?? {}; const inner = asObj(a.arguments) ?? {};
    const r = t.result as Record<string, any>;
    const d = r?.content?.[0]?.data;
    if (!d || d.success !== true || r.isError) return;
    if (a.tool === 'fetch_data') {
      const k = deviceCallKey('fetch_data', inner);
      if (!k.single) return;
      const struct = d.result?.structuredContent?.hosts?.[k.host!];
      if (!struct || struct.success !== true) return;
      if (entries.some((e) => e.tool === 'fetch_data' && e.getter === k.getters![0] && e.host === k.host)) return;
      entries.push({ tool: 'fetch_data', getter: k.getters![0], host: k.host!, result: r, from: { executionId: s.executionId, index } });
    } else if (a.tool === 'list_devices') {
      if (entries.some((e) => e.tool === 'list_devices' && canonicalArgs(e.args ?? {}) === canonicalArgs(inner))) return;
      entries.push({ tool: 'list_devices', args: inner, result: r, from: { executionId: s.executionId, index } });
    }
  });
  // ADDENDUM (f): `lldp_neighbors` (NAPALM get_lldp_neighbors: {iface: [{hostname, port}]}) is PROJECTED from the stored
  // `lldp_neighbors_detail` of the same host (remote_system_name → hostname, remote_port → port). No stored base-rig lldp_neighbors read
  // exists (the only stored ones are the 3-node igp-triangle rig, 2026-08-23). Named departure; the entry carries `derived`.
  for (const d of entries.filter((e) => e.tool === 'fetch_data' && e.getter === 'lldp_neighbors_detail')) {
    if (entries.some((e) => e.getter === 'lldp_neighbors' && e.host === d.host)) continue;
    const env = JSON.parse(JSON.stringify(d.result));
    const host = env?.content?.[0]?.data?.result?.structuredContent?.hosts?.[d.host!];
    const det = host?.output?.lldp_neighbors_detail ?? {};
    const proj: Record<string, Array<{ hostname: string; port: string }>> = {};
    for (const [iface, ns] of Object.entries<any>(det)) proj[iface] = (ns as any[]).map((n) => ({ hostname: n.remote_system_name, port: n.remote_port }));
    host.output = { lldp_neighbors: proj };
    env.content[0].data.arguments = { getters: ['lldp_neighbors'], filter_name: d.host };
    entries.push({ tool: 'fetch_data', getter: 'lldp_neighbors', host: d.host, result: env, from: d.from, derived: 'projection of lldp_neighbors_detail (hostname ← remote_system_name, port ← remote_port)' });
  }
  return { serviceNames, entries, ...(failure ? { failure } : {}) };
}

/** Identity proof: every pool entry's INNER result equals its stored record's, byte for byte (`JSON.stringify`). */
export function provePool(pool: DevicePool, sources: Map<string, Array<Record<string, any>>>): string[] {
  const bad: string[] = [];
  for (const e of pool.entries) {
    if (e.derived) continue; // a derived entry has no record of its own; its source entry is proved
    const st = sources.get(e.from.executionId)?.[e.from.index];
    if (!st || JSON.stringify(st.result?.content?.[0]?.data?.result) !== JSON.stringify(e.result?.content?.[0]?.data?.result)) bad.push(`${e.tool} ${e.getter ?? ''} ${e.host ?? ''} ← ${e.from.executionId}#${e.from.index}`);
  }
  return bad;
}

/** B6: the text the SHIPPING handler throws for a descriptor whose fetch fails post-connect — recomputed, never typed. */
export async function shippingDescriptorRefusal(): Promise<string> {
  const regDecl = require('../../lib/mcp/server/tools/hub/registrant-declaration');
  const { validationError } = require('../../lib/mcp/server/tools/hub/error-helpers');
  const { registerFieldsSchema } = require('../../lib/mcp/server/config/tool-schemas');
  const resolved = await regDecl.resolveFromDescriptor({ descriptorUrl: 'https://raw.githubusercontent.com/paichart/paichart/main/descriptors/ceos-lab-readonly-descriptor.json' },
    { registerFieldsSchema, allowQuery: false, fetch: async () => ({ ok: false, reason: 'descriptor-fetch-failed', preConnect: false, cause: 'lab' }) });
  if (resolved.ok) throw new Error('B6: the stubbed fetch did not refuse');
  // The handler's own call (service-registration-handler.js, the descriptorUrl branch): same example and tip.
  const src = fs.readFileSync(path.resolve(__dirname, '../../lib/mcp/server/tools/hub/service-registration-handler.js'), 'utf8');
  const m = src.match(/throw validationError\(\[resolved\.message\], (\{ descriptorUrl: '[^']+' \}), '([^']+)'\);/);
  if (!m) throw new Error('B6: the handler\'s descriptor refusal call moved — re-derive the example/tip');
  const example = { descriptorUrl: m[1].match(/'([^']+)'/)![1] };
  return validationError([resolved.message], example, m[2]).message;
}

