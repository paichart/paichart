/**
 * Leg replay lab — L-N1 NETWORK FIXTURE TIERS (held-network step 2; LAB-PREREG-L-N1.md §9 B4/B5/B6, ADDENDUM (a)). $0.
 *
 * WHY. Under network-provisioning 1.23.0 a Harvester reads the source each device's `## Device sources` line declares. Three
 * shapes have no production record to replay from, so the recorded tier (recorded-tools.ts) would stub them and the cell would
 * measure the stub, not the text:
 *   B4  L-N-a DEVICE TIER — a `device-read` device's whole-config read (`fetch_data getters:["config"]`, one `filter_name` host)
 *       and the narrow single-getter reads after it, in whatever argument spelling the model chooses (production's own record holds
 *       ONE spelling, e.g. `getters_options.config.retrieve: running`). Served from a POOL of stored production results: each
 *       entry's inner `result` is byte-identical to the record it came from (proved by `n1-fixtures`); only the envelope's
 *       `arguments` echo is the caller's, as the gateway echoes it. Per-node FAILURE mode (`deviceFailure`): every device call
 *       addressing a named host returns a stored, verbatim failed gateway result (`n1-fixtures` reads it from production).
 *   B5  L-N-b CATALOGUE TIER — `registry list|tools` and `services discover|health` for the node's fixture catalogue. On the
 *       registered-service path the Harvester has no descriptor in context and must discover the tools; the stub ("tool calls are
 *       not executed") would distort every such sample. Bodies are the LIVE read-only probe's response objects (2026-10-24,
 *       `fixtures/catalogue.json`), with the catalogue rows substituted (github-service verbatim from the probe;
 *       ceos-lab-readonly from the public descriptor). Wrapped as the embedded server wraps an object result.
 *   B6  REGISTER REFUSAL — `registry register` carrying `descriptorUrl` THROWS the shipping refusal text (produced by the shipping
 *       `resolveFromDescriptor` → `validationError` path with a stubbed fetch; `n1-fixtures` recomputes it and the experiment pins it).
 *
 * WHAT IS NOT SERVED HERE goes to the fallback (the recorded tier, or the stub), unchanged. A device call this tier cannot model
 * (a multi-getter or group-filter read, a host not in the pool) is logged `unserved-device`; a catalogue call naming a service
 * outside the fixture catalogue is logged `unserved-catalogue` — both return the stub, never silently.
 *
 * VALIDITY (prereg §5 "validity", ADDENDUM (a)): a sample counts for content gates only when 100% of its config-getter calls and
 * 100% of its catalogue calls were served by these tiers (a failure-mode answer is served).
 */
import * as fs from 'fs';
import * as path from 'path';
import type { RecordedToolServer, ServeLogEntry } from './recorded-tools';
import { canonicalArgs } from './recorded-tools';

export type NetTier = 'device-pool' | 'device-pool-composed' | 'device-failure' | 'unserved-device' | 'catalogue' | 'unserved-catalogue' | 'register-refused';
export const NET_SERVED: readonly NetTier[] = ['device-pool', 'device-pool-composed', 'device-failure', 'catalogue', 'register-refused'];

export interface DevicePoolEntry { tool: 'fetch_data' | 'list_devices'; getter?: string; host?: string; args?: Record<string, unknown>;
  /** ADDENDUM (f): an entry DERIVED from another stored entry (named), never fetched */ derived?: string;
  /** the stored gateway envelope (result.json toolCalls[i].result), verbatim */ result: Record<string, any>; from: { executionId: string; index: number };
  /** L-CS-N (F14): the rig the stored read came from (`devext` self-host, `prod` lab rig) — named per entry */ rig?: string }
export interface DevicePool { serviceNames: string[]; entries: DevicePoolEntry[]; failure?: { result: Record<string, any>; from: { executionId: string; index: number } } }
export interface CatalogueService { name: string; tools: Record<string, any>; health: Record<string, any>; discoverRow: Record<string, any> }
export interface CatalogueFixture { discoverWrapper: Record<string, any>; listWrapper: Record<string, any>; services: Record<string, CatalogueService> }
export interface NetworkFixtureSpec {
  /** fixture file (relative to the experiment dir): the device pool (B4) */ devicePool?: string;
  /** sha256 of the pool file (it lives in gitignored cache/n1/: regenerated by `n1-fixtures`, proved equal here) */ devicePoolSha256?: string;
  /** B4 failure mode: hosts whose every device call returns the pool's verbatim failed result */ deviceFailureHosts?: string[];
  /** fixture file: the catalogue (B5) */ catalogue?: string;
  /** B5: the services this node's catalogue holds (a subset of the catalogue file's) */ catalogueServices?: string[];
  /** B5 (crib fix, ADDENDUM (c)): descriptor URL → catalogue service that joins the catalogue (tools / health / discover / list) once a
   *  `registry register descriptorUrl` of that URL SUCCEEDS — the platform registers the descriptor's service, so production would then
   *  answer its tools. Without it the crib's descriptor cells read `unserved-catalogue` right after a successful register. */
  catalogueOnRegister?: Record<string, string>;
  /** ADDENDUM (f): descriptor URL → a local copy of the PUBLIC descriptor. A `registry register descriptorUrl` is first run through the
   *  SHIPPING `resolveFromDescriptor` (fetch stubbed to return that copy): a caller-typed SECURITY field (name, endpoint, authType) or
   *  capabilities set that disagrees with the descriptor is REFUSED as production refuses it (DESCRIPTOR_FIELD_DISAGREES, thrown with the
   *  handler's own example and tip). R2 served such a register a recorded success the platform would refuse. */
  descriptorFiles?: Record<string, string>;
  /** B5: a catalogue read naming a service outside the catalogue goes to the fallback (recorded tier) instead of the stub (controls). */
  catalogueFallthrough?: boolean;
  /** B6: refuse `registry register descriptorUrl` with this pinned text (fixture file holding { message }) */ registerRefusal?: string;
}
export interface LoadedNetworkFixture { spec: NetworkFixtureSpec; pool: DevicePool | null; catalogue: CatalogueFixture | null; refusal: string | null; descriptors?: Record<string, unknown> }
export interface NetServeEntry { tier: NetTier; tool: string; action: string | null; innerTool: string | null; target: string | null; getters: string[] | null; host: string | null; detail: string | null }

const parseMaybe = (v: unknown): unknown => { if (typeof v !== 'string') return v; try { return JSON.parse(v); } catch { return v; } };
const asObj = (v: unknown): Record<string, any> | null => { const p = parseMaybe(v); return p && typeof p === 'object' && !Array.isArray(p) ? p as Record<string, any> : null; };

export function loadNetworkFixture(dir: string, spec: NetworkFixtureSpec): LoadedNetworkFixture {
  const read = (f?: string) => (f ? JSON.parse(fs.readFileSync(path.resolve(dir, f), 'utf8')) : null);
  const pool = read(spec.devicePool) as DevicePool | null;
  if (spec.devicePool && spec.devicePoolSha256) {
    const h = require('crypto').createHash('sha256').update(fs.readFileSync(path.resolve(dir, spec.devicePool), 'utf8'), 'utf8').digest('hex');
    if (h !== spec.devicePoolSha256) throw new Error(`L-N-a: ${spec.devicePool} sha256 ${h.slice(0, 12)} ≠ pinned ${spec.devicePoolSha256.slice(0, 12)} — re-run n1-fixtures and compare`);
  }
  const catalogue = read(spec.catalogue) as CatalogueFixture | null;
  const refusal = spec.registerRefusal ? String(read(spec.registerRefusal).message) : null;
  if (spec.deviceFailureHosts?.length && !pool?.failure) throw new Error('L-N-a: deviceFailureHosts without a pool failure result');
  for (const s of [...(spec.catalogueServices ?? []), ...Object.values(spec.catalogueOnRegister ?? {})]) if (!catalogue?.services[s]) throw new Error(`L-N-b: catalogue service ${s} is not in ${spec.catalogue}`);
  if (spec.catalogueServices && !catalogue) throw new Error('L-N-b: catalogueServices without a catalogue file');
  const descriptors: Record<string, unknown> = {};
  for (const [u, f] of Object.entries(spec.descriptorFiles ?? {})) descriptors[u] = JSON.parse(fs.readFileSync(path.resolve(dir, f), 'utf8'));
  return { spec, pool, catalogue, refusal, descriptors };
}

/** ADDENDUM (f): the shipping descriptor check for a `register descriptorUrl` (null ⇒ accepted; else the thrown refusal text). */
export async function shippingDescriptorCheck(args: Record<string, any>, descriptor: unknown): Promise<string | null> {
  const regDecl = require('../../lib/mcp/server/tools/hub/registrant-declaration');
  const { validationError } = require('../../lib/mcp/server/tools/hub/error-helpers');
  const { registerFieldsSchema } = require('../../lib/mcp/server/config/tool-schemas');
  const r = await regDecl.resolveFromDescriptor(args, { registerFieldsSchema, allowQuery: false,
    fetch: async (url: string) => ({ ok: true, json: descriptor, url, storedUrl: url, sha256: 'lab' }) });
  if (r.ok) return null;
  const src = fs.readFileSync(path.resolve(__dirname, '../../lib/mcp/server/tools/hub/service-registration-handler.js'), 'utf8');
  const m = src.match(/throw validationError\(\[resolved\.message\], \{ descriptorUrl: '([^']+)' \}, '([^']+)'\);/);
  if (!m) throw new Error('descriptor check: the handler\'s refusal call moved — re-derive the example/tip');
  return validationError([r.message], { descriptorUrl: m[1] }, m[2]).message;
}

/** The embedded server's wrap of an object result (embedded-server.ts enhanceWithStructuredOutput) + the loop's `_meta`. */
export function embeddedWrap(toolName: string, data: Record<string, unknown>): Record<string, unknown> {
  return { content: [{ type: 'data', data, annotations: { dataType: 'object', itemCount: Object.keys(data).length } }], isError: false,
    _meta: { executionTime: 0, serverName: 'paichart-embedded-mcp', toolName } };
}

/** The device-tier key of a services call: inner tool, single getter, single host — or null when it is not single-target. */
export function deviceCallKey(innerTool: string | null, inner: Record<string, any>): { getters: string[] | null; host: string | null; single: boolean } {
  const getters = Array.isArray(inner.getters) ? inner.getters.map(String) : null;
  const host = typeof inner.filter_name === 'string' ? inner.filter_name : null;
  const single = innerTool === 'fetch_data' ? !!getters && getters.length === 1 && !!host && inner.filter_group === undefined : false;
  return { getters, host, single };
}
const callNamesHost = (inner: Record<string, any>, host: string) => inner.filter_name === host || new RegExp(`(?<![\\w-])${host}(?![\\w-])`).test(JSON.stringify(inner));

/** True when a services call targets the pool's device service (by name or a stored registry id). */
const isDeviceTarget = (pool: DevicePool, target: string | null) => !!target && pool.serviceNames.includes(target);

export interface NetworkToolServer extends RecordedToolServer { netLog: NetServeEntry[] }

/**
 * One server per SAMPLE, wrapping `fallback` (the recorded tier, or null ⇒ `stub`); its log is SHARED with the fallback's so the
 * log stays one entry per executeToolOnServer call, in call order (runHarvesterSample's byte check relies on that).
 */
export function createNetworkToolServer(fx: LoadedNetworkFixture, fallback: RecordedToolServer | null, stub: unknown): NetworkToolServer {
  const log: ServeLogEntry[] = fallback ? fallback.log : [];
  const netLog: NetServeEntry[] = [];
  const cat = fx.catalogue; const catNames = new Set(fx.spec.catalogueServices ?? []); const registeredNow = new Set<string>();
  const record = (e: NetServeEntry, fileTool = false) => { netLog.push(e); log.push({ tool: e.tool, action: e.action, innerTool: e.innerTool, fileTool, tier: e.tier as any, storedIndex: null }); };
  const pass = async (server: string, tool: string, args: unknown) => {
    if (fallback) return fallback.executeToolOnServer(server, tool, args);
    const a = asObj(args);
    log.push({ tool, action: typeof a?.action === 'string' ? a.action : null, innerTool: typeof a?.tool === 'string' ? a.tool : null, fileTool: false, tier: 'unserved', storedIndex: null });
    return stub;
  };
  return {
    log, netLog,
    async getToolDefinition(name: string) { return fallback ? fallback.getToolDefinition(name) : { serverName: 'leg-replay-lab-network', tool: { name } }; },
    async executeToolOnServer(server: string, tool: string, args: unknown) {
      const a = asObj(args) ?? {};
      const action = typeof a.action === 'string' ? a.action : null;
      const base: NetServeEntry = { tier: 'unserved-catalogue', tool, action, innerTool: typeof a.tool === 'string' ? a.tool : null, target: null, getters: null, host: null, detail: null };
      // B6 — the platform refuses the descriptor registration (thrown as the handler throws it; the loop records a failed call).
      if (tool === 'registry' && action === 'register' && a.descriptorUrl !== undefined && fx.refusal) {
        record({ ...base, tier: 'register-refused', detail: String(a.descriptorUrl).slice(0, 200) });
        throw new Error(fx.refusal);
      }
      // ADDENDUM (f) — the shipping descriptor field check runs before any served register.
      if (tool === 'registry' && action === 'register' && typeof a.descriptorUrl === 'string' && fx.descriptors?.[a.descriptorUrl]) {
        const refusal = await shippingDescriptorCheck(a, fx.descriptors[a.descriptorUrl]);
        if (refusal) { record({ ...base, tier: 'register-refused', detail: refusal.split('\n')[0].slice(0, 160) }); throw new Error(refusal); }
      }
      // B5 (ADDENDUM (c)) — a successful descriptor registration adds the descriptor's service to this sample's catalogue.
      if (tool === 'registry' && action === 'register' && typeof a.descriptorUrl === 'string' && fx.spec.catalogueOnRegister?.[a.descriptorUrl]) {
        const res = await pass(server, tool, args); // the recorded register (or the stub); a throw propagates as production's would
        const ok = !!(res as any)?.content?.[0]?.data?.success;
        if (ok) { catNames.add(fx.spec.catalogueOnRegister[a.descriptorUrl]); registeredNow.add(fx.spec.catalogueOnRegister[a.descriptorUrl]); }
        return res;
      }
      // B5 — catalogue reads.
      if (cat && ((tool === 'registry' && (action === 'list' || action === 'tools')) || (tool === 'services' && (action === 'discover' || action === 'health')))) {
        const name = String(a.service_name ?? a.serviceId ?? a.service_id ?? a.targetService ?? '') || null;
        if (tool === 'registry' && action === 'list') {
          const body = JSON.parse(JSON.stringify(cat.listWrapper));
          const rows = [...registeredNow].map((n) => { const r = cat.services[n].discoverRow; return { id: r.id, name: r.name, description: r.description, version: r.version, status: 'ACTIVE', responseTime: r.responseTime, successRate: r.successRate, lastHeartbeat: r.lastHeartbeat, createdAt: r.createdAt, updatedAt: r.createdAt }; });
          body.services = rows; body.total = rows.length; body.returned = rows.length;
          if (body.quota) { body.quota.used = rows.length; body.quota.free = (body.quota.limit ?? 10) - rows.length; body.quota.active = rows.length; body.quota.byStatus = rows.length ? { ACTIVE: rows.length } : {}; }
          if (rows.length && Array.isArray(body.nextSteps)) body.nextSteps = [`Managing ${rows.length} service${rows.length > 1 ? 's' : ''}`, ...rows.map((r) => `Check health: services(action: 'health', service_name: '${r.name}')`)];
          record({ ...base, tier: 'catalogue', detail: `list ${rows.length}` });
          return embeddedWrap('registry', body);
        }
        if (tool === 'services' && action === 'discover') {
          const q = String(a.capability ?? '').toLowerCase(); const cg = String(a.category ?? '').toLowerCase();
          const rows = [...catNames].map((n) => cat.services[n]).filter((s) => {
            const hay = JSON.stringify([s.discoverRow.name, s.discoverRow.description, s.discoverRow.capabilities]).toLowerCase();
            return (!q || q.split(/\s+/).some((w) => hay.includes(w))) && (!cg || String(s.discoverRow.configuration?.category ?? '').toLowerCase() === cg);
          }).map((s) => s.discoverRow);
          const body = JSON.parse(JSON.stringify(cat.discoverWrapper));
          body.services = rows; body.total = rows.length; body.returned = rows.length;
          if (body.pagination) { body.pagination.total = rows.length; body.pagination.returned = rows.length; }
          record({ ...base, tier: 'catalogue', detail: `discover ${rows.length}` });
          return embeddedWrap('services', body);
        }
        if (name && catNames.has(name)) {
          const s = cat.services[name];
          record({ ...base, tier: 'catalogue', target: name, detail: action });
          return embeddedWrap(tool, action === 'tools' ? s.tools : s.health);
        }
        if (fx.spec.catalogueFallthrough) return pass(server, tool, args);
        record({ ...base, tier: 'unserved-catalogue', target: name, detail: `${action} of a service outside the fixture catalogue` });
        return stub;
      }
      // B4 — device reads.
      const pool = fx.pool;
      const target = typeof a.targetService === 'string' ? a.targetService : null;
      if (pool && tool === 'services' && (action === 'call' || action === null) && isDeviceTarget(pool, target)) {
        const inner = asObj(a.arguments) ?? {};
        const k = deviceCallKey(base.innerTool, inner);
        const e: NetServeEntry = { ...base, tier: 'unserved-device', target, getters: k.getters, host: k.host };
        const failHost = (fx.spec.deviceFailureHosts ?? []).find((h) => callNamesHost(inner, h));
        if (failHost && pool.failure) { record({ ...e, tier: 'device-failure', detail: failHost }); return pool.failure.result; }
        let hit: DevicePoolEntry | undefined;
        if (base.innerTool === 'fetch_data' && k.single) hit = pool.entries.find((x) => x.tool === 'fetch_data' && x.getter === k.getters![0] && x.host === k.host);
        // ADDENDUM (c): a single-host multi-getter read is COMPOSED from the pool's single-getter entries for that host (each getter's
        // output verbatim; the envelope of the first). Named divergence: the real service answers one call, the pool holds separate ones.
        if (base.innerTool === 'fetch_data' && !k.single && k.getters && k.getters.length > 1 && k.host && inner.filter_group === undefined) {
          const parts = k.getters.map((g) => pool.entries.find((x) => x.tool === 'fetch_data' && x.getter === g && x.host === k.host));
          if (parts.every(Boolean)) {
            const env = JSON.parse(JSON.stringify(parts[0]!.result));
            const d = env?.content?.[0]?.data;
            const out: Record<string, unknown> = {};
            for (const p of parts) Object.assign(out, p!.result?.content?.[0]?.data?.result?.structuredContent?.hosts?.[k.host]?.output ?? {});
            if (d?.result?.structuredContent?.hosts?.[k.host]) d.result.structuredContent.hosts[k.host].output = out;
            if (d && typeof d === 'object') { d.arguments = inner; d.targetService = target; }
            record({ ...e, tier: 'device-pool-composed', detail: parts.map((p) => `${p!.from.executionId}#${p!.from.index}`).join('+') });
            return env;
          }
        }
        if (base.innerTool === 'list_devices') hit = pool.entries.find((x) => x.tool === 'list_devices' && canonicalArgs(x.args ?? {}) === canonicalArgs(inner));
        if (hit) {
          const env = JSON.parse(JSON.stringify(hit.result));
          const d = env?.content?.[0]?.data;
          if (d && typeof d === 'object') { d.arguments = inner; d.targetService = target; }
          record({ ...e, tier: 'device-pool', detail: `${hit.from.executionId}#${hit.from.index}` });
          return env;
        }
        if (base.innerTool === 'fetch_data' || base.innerTool === 'list_devices') { record({ ...e, detail: k.single ? 'not in the pool' : 'not single-target' }); return stub; }
      }
      return pass(server, tool, args);
    },
  };
}

export interface NetworkToolsReport { calls: number; tiers: Partial<Record<NetTier, number>>; configCalls: number; configServed: number; catalogueCalls: number; catalogueServed: number; valid: boolean; log: NetServeEntry[] }
export function networkToolsReport(netLog: NetServeEntry[]): NetworkToolsReport {
  const tiers: Partial<Record<NetTier, number>> = {};
  for (const e of netLog) tiers[e.tier] = (tiers[e.tier] ?? 0) + 1;
  const config = netLog.filter((e) => e.innerTool === 'fetch_data' && (e.getters ?? []).includes('config'));
  const catalogue = netLog.filter((e) => e.tier === 'catalogue' || e.tier === 'unserved-catalogue');
  const configServed = config.filter((e) => NET_SERVED.includes(e.tier)).length;
  const catalogueServed = catalogue.filter((e) => e.tier === 'catalogue').length;
  return { calls: netLog.length, tiers, configCalls: config.length, configServed, catalogueCalls: catalogue.length, catalogueServed,
    valid: configServed === config.length && catalogueServed === catalogue.length, log: netLog };
}

