/**
 * Leg replay lab — the in-run requirements check's DATA as it stood at a commit (L-Z2, 2026-10-10, Z49 lab gate).
 *
 * The requirements_author in-run check (`computeRequirementsFormCheckStamp`, and through it the 2b correction turn) reads
 * two generated constants: the decision REGISTRY (coverage: which rows each leg class must carry, and their options) and
 * the TEMPLATE text (the lint allowlist base). Both live in `lib/agents/harness/requirements-form-check.generated.ts`.
 * A change that adds a registry row (Z49: `<token>.request-path`) ships the row in the check AND in the Author's text, so
 * an arm that replays TODAY's production must also run TODAY's check data — otherwise the base arm's correction turn is
 * told to add a row production does not yet ask for, and the control is contaminated.
 *
 * `variant.requirementsCheckAt: "<commit>"` runs that arm's in-run check (and its scoring) on the generated data at that
 * commit. The CODE stays HEAD's: only the four data constants are swapped, in place, on the live module. Samples of
 * different check data never interleave: `run` executes one data group at a time and restores HEAD's data after each
 * (see lab.ts); scoring is synchronous, so a swap around each cell is exact.
 *
 * Every sample's stamp records which data ran (`requirementsFormCheck.registrySha256` / `templateSha256`), and
 * `useCheckDataAt` returns the shas it installed, so a reader can check them against the manifest.
 */
import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import { CACHE_DIR } from './snapshot';

const REPO = path.resolve(__dirname, '..', '..');
const GEN_REL = 'lib/agents/harness/requirements-form-check.generated.ts';
// eslint-disable-next-line @typescript-eslint/no-var-requires
const LIVE: Record<string, any> = require('../../lib/agents/harness/requirements-form-check.generated');
const KEYS = ['REQUIREMENTS_REGISTRY', 'REQUIREMENTS_REGISTRY_SHA256', 'REQUIREMENTS_TEMPLATE_SHA256', 'REQUIREMENTS_TEMPLATE_TEXT'] as const;
const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v));
const HEAD_DATA: Record<string, any> = Object.fromEntries(KEYS.map((k) => [k, clone(LIVE[k])]));

function git(args: string[]): string { return execFileSync('git', ['-C', REPO, ...args], { maxBuffer: 256 * 1024 * 1024 }).toString(); }

export function resolveCommit(commit: string): string {
  if (!/^[0-9a-f]{7,40}(~\d+)?$|^HEAD(~\d+)?$/.test(commit)) throw new Error(`requirementsCheckAt: not a commit: ${commit}`);
  return git(['rev-parse', commit]).trim();
}

/** The four data constants of the generated module at `commit` (cached under cache/check-at/; never written to lib/). */
export function checkDataAt(commit: string): Record<string, any> {
  const full = resolveCommit(commit);
  const dir = path.join(CACHE_DIR, 'check-at');
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `generated-${full.slice(0, 12)}.ts`);
  if (!fs.existsSync(file)) {
    // The module's only import is a TYPE import from its own directory: point it at the live file (erased at runtime).
    const src = git(['show', `${full}:${GEN_REL}`]).replace(/from '\.\/requirements-coverage'/, `from '${path.join(REPO, 'lib', 'agents', 'harness', 'requirements-coverage')}'`);
    fs.writeFileSync(file, `// GENERATED by scripts/leg-replay-lab/check-at.ts from ${full}:${GEN_REL} — do not edit\n${src}`);
  }
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const mod = require(file);
  for (const k of KEYS) if (mod[k] === undefined) throw new Error(`requirementsCheckAt ${commit}: ${GEN_REL} exports no ${k}`);
  return Object.fromEntries(KEYS.map((k) => [k, clone(mod[k])]));
}

/** Install the check data of `commit` (null ⇒ HEAD's) on the LIVE module. Returns the installed shas. */
export function useCheckDataAt(commit: string | null | undefined): { registrySha256: string; templateSha256: string; source: string } {
  const data = commit ? checkDataAt(commit) : clone(HEAD_DATA);
  // The registry object is mutated IN PLACE: every consumer holds a reference to it.
  const reg = LIVE.REQUIREMENTS_REGISTRY;
  for (const k of Object.keys(reg)) delete reg[k];
  Object.assign(reg, data.REQUIREMENTS_REGISTRY);
  for (const k of ['REQUIREMENTS_REGISTRY_SHA256', 'REQUIREMENTS_TEMPLATE_SHA256', 'REQUIREMENTS_TEMPLATE_TEXT'] as const) LIVE[k] = data[k];
  for (const k of KEYS) {
    if (JSON.stringify(LIVE[k]) !== JSON.stringify(data[k])) throw new Error(`check-at: ${k} did not take on the live module (export not writable?)`);
  }
  return { registrySha256: LIVE.REQUIREMENTS_REGISTRY_SHA256, templateSha256: LIVE.REQUIREMENTS_TEMPLATE_SHA256, source: commit ? `commit:${resolveCommit(commit).slice(0, 12)}` : 'HEAD' };
}

export function checkDataLabel(commit: string | null | undefined): string { return commit ? `check@${resolveCommit(commit).slice(0, 12)}` : 'check@HEAD'; }
