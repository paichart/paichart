/**
 * Bytes proof for the 2026-10-13 observability quote + consumer lab ($0, offline after the protocol pin).
 *
 *   npx ts-node -r tsconfig-paths/register scripts/leg-replay-lab/inputs/2026-10-13-obs-quote-consumer/bytes-proof.ts [--at <pre-build commit>] [--shipped <commit>|worktree]
 *
 *   P1  the seed at the pre-build commit renders observability-config 1.8.0 byte-identical to the pinned production row;
 *   P2  that seed with DRAFT-C §2 (C1, C2a, C2b) and DRAFT-B §6.3 (CONSUMED_ADDRESS_CLAUSE, observability only) applied
 *       VERBATIM in TS-source form renders byte-identical to the lab's materialized variant (both arms' files), and
 *       moves no other protocol;
 *   P3  observability 1.8.0 rendered identically at every seed commit from 6d2d5b05 (its seed) to the pre-build commit —
 *       the text the 10-12 nodes ran is the pinned text;
 *   P4  (--shipped) the 1.9.0 actually built (a commit, or the working tree) renders byte-identical to the lab variant.
 */
if (!process.env.DATABASE_URL) process.env.DATABASE_URL = 'postgresql://leg-replay-lab:never@127.0.0.1:1/never_connects';
if (!process.env.PAICHART_SKIP_DB_CONNECT) process.env.PAICHART_SKIP_DB_CONNECT = 'true';
if (!process.env.LOG_LEVEL) process.env.LOG_LEVEL = 'warn';
import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import { CACHE_DIR } from '../../snapshot';
import { protocolTextAtCommit } from '../../protocol-history';

const EXP = __dirname;
const REPO = path.resolve(EXP, '..', '..', '..', '..');
const NAME = 'observability-config-protocol';
const argv = process.argv.slice(2);
const val = (k: string) => (argv.includes(k) ? argv[argv.indexOf(k) + 1] : undefined);
const AT = val('--at') ?? '5fde4f3b';
const SHIPPED = val('--shipped');
const git = (a: string[]) => execFileSync('git', ['-C', REPO, ...a], { maxBuffer: 256 * 1024 * 1024 }).toString();
const read = (f: string) => fs.readFileSync(path.join(EXP, f), 'utf8');

function renderSource(src: string, tag: string): Map<string, string> {
  const dir = path.join(CACHE_DIR, 'seed-at'); fs.mkdirSync(dir, { recursive: true });
  const out = src.replace(/from '\.\.\/lib\//g, `from '${path.join(REPO, 'lib')}/`).replace(/__dirname/g, JSON.stringify(path.join(REPO, 'scripts')));
  const f = path.join(dir, `bytes-proof-${tag}-${Date.now()}.ts`);
  fs.writeFileSync(f, `// GENERATED by bytes-proof.ts — do not edit\n${out}`);
  const mod = require(f);
  return new Map((mod.PROTOCOLS as Array<{ name: string; promptText: string }>).map((p) => [p.name, p.promptText]));
}
const once = (hay: string, old: string, neu: string, what: string) => {
  const n = hay.split(old).length - 1;
  if (n !== 1) throw new Error(`${what}: anchor occurs ${n} times`);
  return hay.replace(old, () => neu);
};

let failed = 0;
const check = (id: string, ok: boolean, detail: string) => { if (!ok) failed++; console.log(`${ok ? '✅' : '❌'} ${id} ${detail}`); };

const exp = JSON.parse(read('experiment.json'));
const baseFile = exp.baseline.protocols[NAME].file as string;
const base = read(baseFile);
const variants = ['hobs19', 'obs19'].map((v) => read(baseFile.replace(/\.baseline\.md$/, `.${v}.md`)));

// P1
const atText = protocolTextAtCommit(NAME, AT);
check('P1', atText.version === '1.8.0' && atText.text === base, `seed at ${AT} renders ${NAME}@${atText.version} ${atText.text === base ? '==' : '≠'} pinned production row (${base.length} chars)`);

// P2 — the drafts' own code blocks, applied verbatim to the TS source.
const draftC = fs.readFileSync(path.join(REPO, 'cline_docs/reviews/verbatim-quote-omission-2026-10-13/DRAFT-C.md'), 'utf8');
const draftB = fs.readFileSync(path.join(REPO, 'cline_docs/reviews/containment-propagation-2026-10-12/DRAFT-B.md'), 'utf8');
const blocks = [...draftC.matchAll(/```(?:ts)?\n([\s\S]*?)\n```/g)].map((m) => m[1]);
const [c1, c2aOld, c2aNew, c2bOld, c2bNew] = blocks;
const tsBlock = /```ts\n([\s\S]*?)\n```/.exec(draftB.split('### 6.3')[1])![1];
const constLine = tsBlock.split('\n').find((l) => l.startsWith('const CONSUMED_ADDRESS_CLAUSE'))!;
const src = git(['show', `${AT}:scripts/seed-protocol-prompts.ts`]);
const start = src.indexOf('const PIPELINE_OBSERVABILITY_CONFIG_PROTOCOL = `');
const end = src.indexOf('\n`;', start);
let obs = src.slice(start, end);
obs = once(obs, 'Read-only only; never a write or lifecycle verb.', `Read-only only; never a write or lifecycle verb.${c1}`, 'C1');
obs = once(obs, c2aOld, c2aNew, 'C2a');
obs = once(obs, c2bOld, c2bNew, 'C2b');
const anchor = 'so a coined kind turns a correct value into a false mismatch. ';
obs = once(obs, anchor, `${anchor}\${CONSUMED_ADDRESS_CLAUSE} `, 'consumer interpolation');
let cand = src.slice(0, start) + obs + src.slice(end);
const mp = cand.indexOf('const MARKER_PLACEMENT_CLAUSE');
const mpEnd = cand.indexOf('\n', cand.indexOf('`;', mp));
cand = `${cand.slice(0, mpEnd + 1)}\n${constLine}\n${cand.slice(mpEnd + 1)}`;
const before = renderSource(src, 'at');
const after = renderSource(cand, 'cand');
const moved = [...after.keys()].filter((k) => after.get(k) !== before.get(k));
const candText = after.get(NAME)!;
check('P2', variants.every((v) => v === candText) && moved.length === 1 && moved[0] === NAME,
  `TS-source edits render ${candText.length} chars (+${candText.length - base.length}); == hobs19/obs19 files: ${variants.map((v) => v === candText).join('/')}; protocols moved: ${moved.join(', ') || 'none'}`);

// P3
const commits = git(['log', '--format=%h', `6d2d5b05^..${AT}`, '--', 'scripts/seed-protocol-prompts.ts']).trim().split('\n').filter(Boolean);
const bad = commits.filter((c) => { const t = protocolTextAtCommit(NAME, c); return t.version !== '1.8.0' || t.text !== base; });
check('P3', bad.length === 0, `${NAME} 1.8.0 identical at ${commits.length} seed commits 6d2d5b05..${AT}${bad.length ? ` — differs at ${bad.join(', ')}` : ''}`);

// P4
if (SHIPPED) {
  const shippedSrc = SHIPPED === 'worktree' ? fs.readFileSync(path.join(REPO, 'scripts/seed-protocol-prompts.ts'), 'utf8') : git(['show', `${SHIPPED}:scripts/seed-protocol-prompts.ts`]);
  const s = renderSource(shippedSrc, 'shipped').get(NAME)!;
  check('P4', s === candText, `${NAME} as built at ${SHIPPED} (${s.length} chars) ${s === candText ? '==' : '≠'} the lab variant`);
}
process.exit(failed ? 1 : 0);
