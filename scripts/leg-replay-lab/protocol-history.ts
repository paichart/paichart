/**
 * Leg replay lab — protocol text AS IT STOOD at a past version, rendered from the seed at a git commit.
 *
 * Production keeps only the CURRENT row of each protocol. To replay an execution under the text it actually ran
 * with (e.g. observability-config 1.5.0, retired 2026-10-04), the lab extracts `scripts/seed-protocol-prompts.ts`
 * at a commit with `git show`, rewrites its two path-relative references (`../lib/` imports and `__dirname`) to
 * absolute paths, and requires it — the seed has guarded `main()` behind `require.main === module` since
 * 88a3939c (2026-10-02, when `PROTOCOLS` was exported), so requiring it writes nothing.
 *
 * WHICH COMMIT: the newest commit that touched the seed at or before the execution's start time AND renders the
 * protocol at the version the execution stamped. A version match is necessary, not sufficient (text can move
 * without a bump), which is why the lab never trusts this on its own: `protocolInjection.preambleChars` on the
 * persisted execution is compared against the rebuilt prompt, and a mismatch is reported, not absorbed.
 *
 * Commits before 88a3939c do not export PROTOCOLS and are refused by name.
 */
import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import { CACHE_DIR } from './snapshot';

const REPO = path.resolve(__dirname, '..', '..');
const SEED = 'scripts/seed-protocol-prompts.ts';

function git(args: string[]): string {
  return execFileSync('git', ['-C', REPO, ...args], { maxBuffer: 256 * 1024 * 1024 }).toString();
}

export function renderProtocolsAtCommit(commit: string): Array<{ name: string; version: string; promptText: string }> {
  if (!/^[0-9a-f]{7,40}$/.test(commit)) throw new Error(`not a commit: ${commit}`);
  const full = git(['rev-parse', commit]).trim();
  const dir = path.join(CACHE_DIR, 'seed-at');
  fs.mkdirSync(dir, { recursive: true });
  // v2 (2026-10-10, Z49): `__dirname` resolves to a per-commit copy of `scripts/seed-data/` AT THAT COMMIT. v1 pointed it
  // at the WORKING TREE, so a protocol that embeds a seed-data file (requirements-authoring embeds
  // seed-data/requirements-skeleton.tmpl) rendered TODAY's file at every past commit — found when the 1.8.0 render at
  // 452dfe15 came out byte-identical to the 1.9.0 render. Commits with no seed-data/ keep the working-tree directory.
  const file = path.join(dir, `seed-${full.slice(0, 12)}-v2.ts`);
  if (!fs.existsSync(file)) {
    let src = git(['show', `${full}:${SEED}`]);
    if (!/export const PROTOCOLS\b/.test(src)) throw new Error(`seed at ${commit} does not export PROTOCOLS (pre-88a3939c) — render by hand`);
    let scriptsDir = path.join(REPO, 'scripts');
    const dataFiles = git(['ls-tree', '-r', '--name-only', full, '--', 'scripts/seed-data/']).split('\n').filter(Boolean);
    if (dataFiles.length) {
      scriptsDir = path.join(dir, `scripts-${full.slice(0, 12)}`);
      for (const f of dataFiles) {
        const dest = path.join(scriptsDir, path.relative('scripts', f));
        fs.mkdirSync(path.dirname(dest), { recursive: true });
        fs.writeFileSync(dest, execFileSync('git', ['-C', REPO, 'show', `${full}:${f}`], { maxBuffer: 256 * 1024 * 1024 }));
      }
    }
    src = src.replace(/from '\.\.\/lib\//g, `from '${path.join(REPO, 'lib')}/`)
      .replace(/__dirname/g, JSON.stringify(scriptsDir));
    fs.writeFileSync(file, `// GENERATED by scripts/leg-replay-lab/protocol-history.ts from ${full}:${SEED} — do not edit\n${src}`);
  }
  const mod = require(file);
  return (mod.PROTOCOLS as Array<{ name: string; version: string; promptText: string }>).map((p) => ({ name: p.name, version: p.version, promptText: p.promptText }));
}

/** The newest seed commit at or before `beforeIso` that renders `name` at `version` (scans back `maxScan` seed commits). */
export function findCommitForVersion(name: string, version: string, beforeIso: string, maxScan = 12): string | null {
  const commits = git(['log', `--before=${beforeIso}`, '--format=%H', '-n', String(maxScan), '--', SEED]).trim().split('\n').filter(Boolean);
  for (const c of commits) {
    let rows: Array<{ name: string; version: string }>;
    try { rows = renderProtocolsAtCommit(c); } catch { continue; }
    const row = rows.find((r) => r.name === name);
    if (row && row.version === version) return c;
  }
  return null;
}

export function protocolTextAtCommit(name: string, commit: string): { version: string; text: string } {
  const row = renderProtocolsAtCommit(commit).find((r) => r.name === name);
  if (!row) throw new Error(`${name} not in the seed at ${commit}`);
  return { version: row.version, text: row.promptText };
}
